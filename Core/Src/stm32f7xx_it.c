/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
  
  //判断是否进入空闲中断
  if(__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE) != RESET) {
      //清楚空闲中断标志
      __HAL_UART_CLEAR_FLAG(&huart1, UART_FLAG_IDLE);

      //停止dma再搬运数据
      HAL_UART_DMAStop(&huart1);

      //计算dma搬运数据的长度
      uint16_t rx_len = BUFSIZE - __HAL_DMA_GET_COUNTER(&hdma_usart1_rx);

      //做一个安全机制，防止数组越界造成栈溢出
      if(rx_len > 0 && rx_len < BUFSIZE) {
        Circular_Buf_Put(Rx_Cir_BufHandle, dma_buf, rx_len);  //把数据传入到环形缓冲区
        Circular_Buf_Put_1B(Rx_Cir_BufHandle, (uint8_t)'\0');
        cmd_flag = 1;
      }
      
      //启动dma搬运
      HAL_UART_Receive_DMA(&huart1, dma_buf, BUFSIZE);
  }

  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

  /* USER CODE END USART1_IRQn 1 */
}

